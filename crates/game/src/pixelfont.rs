/// Advance of the small font in pixels (fixed width).
pub const SMALL_ADVANCE: u32 = 10;
/// Advance of the large font.
pub const LARGE_ADVANCE: u32 = 24;

/// Image of `c` in a set (upper-cased first).
pub fn image(set: &[(char, u32)], c: char) -> Option<u32> {
    let u = c.to_uppercase().next().unwrap_or(c);
    set.iter().find(|(k, _)| *k == u).map(|(_, n)| *n)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn letters_and_digits_are_complete() {
        for c in ('A'..='Z').chain('0'..='9') {
            assert!(image(SMALL, c).is_some(), "small {c}");
            assert!(image(LARGE, c).is_some(), "large {c}");
        }
        assert_eq!(image(SMALL, 'b'), Some(3142));
    }
}
